import { mkdir, readdir, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const rootDirectory = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const scannedDirectories = ["src/app", "src/components", "src/lib", "public", "Image"];
const includedExtensions = new Set([
  ".css",
  ".ico",
  ".jpg",
  ".jpeg",
  ".png",
  ".svg",
  ".ts",
  ".tsx",
  ".webp",
  ".woff2",
]);
const outputPath = path.join(rootDirectory, "src", "generated", "sitemap-last-modified.ts");

async function readNewestModifiedTime() {
  let newestModifiedTime = 0;
  const pendingDirectories = scannedDirectories.map((directory) => path.join(rootDirectory, directory));

  while (pendingDirectories.length > 0) {
    const directory = pendingDirectories.pop();

    try {
      const entries = await readdir(directory, { withFileTypes: true });

      for (const entry of entries) {
        const entryPath = path.join(directory, entry.name);

        if (entry.isDirectory()) {
          pendingDirectories.push(entryPath);
          continue;
        }

        if (!entry.isFile() || !includedExtensions.has(path.extname(entry.name).toLowerCase())) {
          continue;
        }

        const fileStats = await stat(entryPath);
        newestModifiedTime = Math.max(newestModifiedTime, fileStats.mtimeMs);
      }
    } catch (error) {
      if (error?.code !== "ENOENT") {
        throw error;
      }
    }
  }

  return newestModifiedTime || Date.now();
}

const sitemapLastModified = new Date(await readNewestModifiedTime()).toISOString();
const generatedSource = `// Generated by scripts/update-sitemap-lastmod.mjs before each build.
export const sitemapLastModified = "${sitemapLastModified}";
`;

await mkdir(path.dirname(outputPath), { recursive: true });
await writeFile(outputPath, generatedSource);
console.log(`Updated sitemap lastmod: ${sitemapLastModified}`);
